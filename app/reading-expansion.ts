const thesis: Meta = { jp: '主張理解（長文）', itemType: 'Thematic reading' };
const search: Meta = { jp: '情報検索', itemType: 'Information retrieval' };

/** Real JLPT passages commonly carry two questions. Keeping the passage shared
 *  while changing the evidence being tested produces authentic close reading,
 *  not two cosmetic rewrites of the same item. */
function pair(meta: Meta, passage: string[], first: QuestionPart, second: QuestionPart): Passage[] {
  return [first, second].map((question) => ({ ...meta, passage: passage.map((line) => [line]), ...question }));
}

