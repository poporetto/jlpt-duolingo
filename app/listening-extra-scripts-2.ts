import type { Level, NarrationLine } from './levels';
import type { Script } from './listening-scripts.ts';

/**
 * The second batch of listening scripts, appended as its own block for the same
 * reason as the first: saved progress is keyed by index, so a new batch never
 * grows an earlier one.
 *
 * Written through a small helper so the frame is identical everywhere: the
 * scene and question are read before the dialogue and the question again after
 * it, with the pauses the rest of the bank uses. Lines are 'w:' or 'm:'; the
 * speaker who answers the question, or does what it asks about, carries the
 * gender the question names. 概要理解 asks nothing before the audio.
 */
type Kind = 'task' | 'point' | 'summary' | 'quick' | 'integrated';
const META: Record<Kind, { jp: string; itemType: string }> = {
  task: { jp: '課題理解', itemType: 'Task comprehension' },
  point: { jp: 'ポイント理解', itemType: 'Point comprehension' },
  summary: { jp: '概要理解', itemType: 'Summary comprehension' },
  quick: { jp: '即時応答', itemType: 'Quick response' },
  integrated: { jp: '統合理解', itemType: 'Integrated listening' },
};
const QUICK_PROMPT: Record<Level, string> = {
  N5: 'きいて、いちばん　いい　へんじを　えらんで　ください。',
  N4: 'きいて、いちばん　いい　へんじを　えらんで　ください。',
  N3: '聞いて、いちばん　いい　返事を　選んで　ください。',
  N2: '聞いて、最も　よい　返事を　選んで　ください。',
  N1: '聞いて、最も　よい　返事を　選んで　ください。',
};

const line = (raw: string, pauseAfter: number): NarrationLine => ({
  speaker: raw.startsWith('w:') ? 'woman' : 'man',
  text: raw.slice(2),
  pauseAfter,
});

/** A dialogue or monologue with the question framed around it. */
function item(kind: Kind, scene: string, question: string, lines: string[], options: string[], note: string): Script {
  const { jp, itemType } = META[kind];
  const body = lines.map((raw, i) => line(raw, i === lines.length - 1 ? 650 : 300));
  const opening = kind === 'summary' || kind === 'integrated' ? scene : `${scene}${question}`;
  return {
    jp, itemType, prompt: question,
    narration: [{ speaker: 'narrator', text: opening, pauseAfter: 700 }, ...body, { speaker: 'narrator', text: question }],
    options, note,
  };
}

/** 即時応答: one utterance and four replies. */
function quick(level: Level, raw: string, options: string[], note: string): Script {
  return { ...META.quick, prompt: QUICK_PROMPT[level], narration: [line(raw, 0)].map(({ speaker, text }) => ({ speaker, text })), options, note };
}

